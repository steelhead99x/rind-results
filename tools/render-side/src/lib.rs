//! Write a side BENCHMARKS.md for hosts outside `admin/bench-report`'s
//! `HOSTS`, matching `render-side.py`.

use serde_json::{Map, Value};
use std::fs;
use std::path::{Component, Path, PathBuf};
use std::process::Command;

const GENERATED: &str = "<!-- Generated by `admin/bench-report render` from benchmarks/data, \
benchmarks/verified.toml, and benchmarks/gaps.toml. -->";
const GENERATED_SIDE: &str = "<!-- Generated by calling report() in rind's admin/bench-report on host \
JSON from outside that script's HOSTS. This is not the repo's BENCHMARKS.md. -->";
const PINNED: &str = "Each host builds with the pinned toolchain in the Nix dev shell, and runs \
`admin/bench-report` only when idle. Times are criterion's estimates.";
const PINNED_SIDE: &str = "Times are criterion's estimates from `admin/bench-report run`. A host measured \
through host-run.py kept that script's operations, criterion arguments, parsing, \
and JSON, and recorded a busy host or a rustc other than the Nix pin instead of \
refusing them. The toolchain and the load are whatever each host's JSON records. \
A host run outside the Nix dev shell, or while other work was on the machine, says \
so in its note. A host the JSON marks noisy had other work during the run.";

pub struct RenderArgs {
    pub rind: PathBuf,
    pub out: PathBuf,
    pub notes: Vec<(String, PathBuf)>,
    pub json: Vec<PathBuf>,
}

pub struct Rendered {
    pub sheet: PathBuf,
}

#[derive(Clone)]
struct Gap {
    row: String,
    host: String,
    ratio: f64,
    best: String,
}

struct ReportOut {
    files: Vec<(PathBuf, String)>,
    gaps: Vec<Gap>,
    columns: Map<String, Value>,
    labels: Map<String, Value>,
}

pub fn render(args: &RenderArgs) -> Result<Rendered, String> {
    let rind = resolve_path(&args.rind)?;
    let out = resolve_path(&args.out)?;
    if !outside(&rind, &out) {
        return Err(
            "render-side: --out is inside the rind checkout; pick a directory outside it".into(),
        );
    }

    let mut notes: Map<String, Value> = Map::new();
    for (name, path) in &args.notes {
        notes.insert(name.clone(), Value::String(read_note(path)?));
    }

    let mut hosts = Map::new();
    let mut table = Map::new();
    for path in &args.json {
        let (name, host) = load_host(path)?;
        if hosts.contains_key(&name) {
            return Err(format!("render-side: two files are named {name}"));
        }
        let beside = path.with_extension("note");
        if !notes.contains_key(&name) && beside.is_file() {
            notes.insert(name.clone(), Value::String(read_note(&beside)?));
        }
        let mut entry = Map::new();
        if let Some(note) = notes.get(&name) {
            entry.insert("note".into(), note.clone());
        }
        table.insert(name.clone(), Value::Object(entry));
        hosts.insert(name, host);
    }
    let unused: Vec<&str> = notes
        .keys()
        .filter(|name| !hosts.contains_key(*name))
        .map(String::as_str)
        .collect();
    if !unused.is_empty() {
        return Err(format!(
            "render-side: notes for hosts with no JSON: {}",
            unused.join(", ")
        ));
    }

    let report = out.join("BENCHMARKS.md");
    let report_dir = out.join("benchmarks");
    let mut produced = call_report(&rind, &hosts, &table, &report, &report_dir)?;
    let sheet = report.clone();
    let rewritten = {
        let content = produced
            .files
            .iter()
            .find(|(path, _)| path == &sheet)
            .map(|(_, content)| content.as_str());
        match content {
            Some(content) => Some(rewrite(content, &produced, &hosts)?),
            None => None,
        }
    };
    let rewritten = match rewritten {
        Some(text) => text,
        None => return Err("render-side: report() did not return the sheet".into()),
    };
    for (path, content) in &mut produced.files {
        if path == &sheet {
            *content = rewritten;
            break;
        }
    }

    for (dest, content) in &produced.files {
        if !outside(&rind, dest) {
            return Err(format!(
                "render-side: refused to write inside the rind checkout: {}",
                dest.display()
            ));
        }
        if let Some(parent) = dest.parent() {
            if !parent.as_os_str().is_empty() {
                fs::create_dir_all(parent)
                    .map_err(|err| format!("render-side: {}: {err}", parent.display()))?;
            }
        }
        let text = if content.ends_with('\n') {
            content.clone()
        } else {
            format!("{content}\n")
        };
        fs::write(dest, text).map_err(|err| format!("render-side: {}: {err}", dest.display()))?;
    }
    Ok(Rendered { sheet: report })
}

fn load_host(path: &Path) -> Result<(String, Value), String> {
    let text = fs::read_to_string(path)
        .map_err(|err| format!("render-side: {}: {err}", path.display()))?;
    let host: Value = serde_json::from_str(&text)
        .map_err(|err| format!("render-side: {}: {err}", path.display()))?;
    let status = host.get("status").and_then(Value::as_str).unwrap_or("");
    if status != "ok" {
        let reason = host
            .get("reason")
            .and_then(Value::as_str)
            .unwrap_or("not ok");
        // Python: host.get("status") of a missing key is None, printed as None.
        let status_shown = match host.get("status") {
            None | Some(Value::Null) => "None".to_string(),
            Some(Value::String(s)) => s.clone(),
            Some(other) => other.to_string(),
        };
        return Err(format!(
            "render-side: {}: status {status_shown}: {reason}",
            path.display()
        ));
    }
    let name = host.get("host").and_then(Value::as_str).unwrap_or("");
    if name.is_empty() || name.chars().any(|c| c.is_whitespace() || c == '`') {
        return Err(format!(
            "render-side: {}: host name must be a token without spaces or backticks",
            path.display()
        ));
    }
    for key in ["results", "started", "commit", "os"] {
        if host.get(key).is_none() {
            return Err(format!("render-side: {}: missing {key}", path.display()));
        }
    }
    let cpu = host.get("cpu").and_then(Value::as_object);
    match cpu {
        Some(cpu) if cpu.contains_key("model") && cpu.contains_key("arch") => {}
        _ => {
            return Err(format!(
                "render-side: {}: missing cpu.model or cpu.arch",
                path.display()
            ));
        }
    }
    if host
        .get("toolchain")
        .and_then(Value::as_object)
        .and_then(|t| t.get("rustc"))
        .is_none()
    {
        return Err(format!(
            "render-side: {}: missing toolchain.rustc",
            path.display()
        ));
    }
    Ok((name.to_string(), host))
}

fn read_note(path: &Path) -> Result<String, String> {
    let text = fs::read_to_string(path)
        .map_err(|err| format!("render-side: {}: {err}", path.display()))?;
    let text = text.trim();
    if text.is_empty() {
        return Err(format!("render-side: {}: empty note", path.display()));
    }
    if text.starts_with('#') || text.contains("\n#") {
        return Err(format!(
            "render-side: {}: a note is prose, not a Markdown heading",
            path.display()
        ));
    }
    Ok(text.to_string())
}

fn rewrite(
    markdown: &str,
    report: &ReportOut,
    hosts: &Map<String, Value>,
) -> Result<String, String> {
    let mut markdown = markdown.to_string();
    for (old, new, what) in [
        (GENERATED, GENERATED_SIDE, "generated-by comment"),
        (PINNED, PINNED_SIDE, "toolchain sentence"),
    ] {
        if !markdown.contains(old) {
            return Err(format!(
                "render-side: report() no longer contains the {what} this script replaces"
            ));
        }
        markdown = markdown.replacen(old, new, 1);
    }
    let marker = "## CPU tiers";
    let verified = "## Verified code";
    if !markdown.contains(marker) || !markdown.contains(verified) {
        return Err("render-side: report() no longer has the sections this script replaces".into());
    }
    let (head, rest) = markdown
        .split_once(marker)
        .ok_or_else(|| "render-side: missing CPU tiers heading".to_string())?;
    let (_, tail) = rest
        .split_once(verified)
        .ok_or_else(|| "render-side: missing Verified code heading".to_string())?;

    let mut lines = vec![
        "## Gaps on these hosts".to_string(),
        String::new(),
        "Each operation where another library is more than 10% faster than rind, \
computed by `gaps_of` the way `admin/bench-report` computes gaps (`SLOWER` is 1.1). \
These are measurements. `benchmarks/gaps.toml` holds the maintainers' decisions for \
the hosts in `HOSTS`, and this sheet does not read or write it."
            .to_string(),
        String::new(),
    ];
    if report.gaps.is_empty() {
        lines.push("None.".into());
    } else {
        lines.push("| Operation | On | rind's time over the fastest |".into());
        lines.push("|---|---|---|".into());
        let order: Vec<&str> = hosts.keys().map(String::as_str).collect();
        let mut ranked = report.gaps.clone();
        ranked.sort_by(|a, b| {
            let ai = order
                .iter()
                .position(|h| *h == a.host)
                .unwrap_or(usize::MAX);
            let bi = order
                .iter()
                .position(|h| *h == b.host)
                .unwrap_or(usize::MAX);
            ai.cmp(&bi).then_with(|| {
                b.ratio
                    .partial_cmp(&a.ratio)
                    .unwrap_or(std::cmp::Ordering::Equal)
            })
        });
        for gap in ranked {
            let shown = report
                .columns
                .get(&gap.best)
                .and_then(Value::as_str)
                .unwrap_or(&gap.best);
            let label = report
                .labels
                .get(&gap.row)
                .and_then(Value::as_str)
                .unwrap_or(&gap.row);
            lines.push(format!(
                "| {label} | `{host}` | {ratio}× ({shown}) |",
                host = gap.host,
                ratio = format_ratio(gap.ratio)
            ));
        }
    }
    Ok(format!(
        "{head}{}\n\n## Verified code{tail}",
        lines.join("\n")
    ))
}

fn format_ratio(x: f64) -> String {
    format!("{x:.2}")
}

const DRIVER: &str = r#"
import importlib.machinery, importlib.util, json, sys

req = json.load(sys.stdin)
path = req["bench_report"]
loader = importlib.machinery.SourceFileLoader("bench_report", path)
spec = importlib.util.spec_from_loader("bench_report", loader)
module = importlib.util.module_from_spec(spec)
loader.exec_module(module)
needed = ("report", "load_verified", "gaps_of", "label", "COLUMNS", "HOSTS", "REPORT", "REPORT_DIR")
missing = [name for name in needed if not hasattr(module, name)]
if missing:
    sys.stderr.write(
        "render-side: admin/bench-report is missing "
        + ", ".join(missing)
        + "; this script is out of date\n"
    )
    sys.exit(1)
module.HOSTS = req["table"]
module.REPORT = req["report"]
module.REPORT_DIR = req["report_dir"]
verified = module.load_verified()
# hosts must keep the request's insertion order (Python 3.7+ dict)
hosts = req["hosts"]
files = module.report(hosts, None, verified, None)
gaps = []
labels = {}
for (row, host), (ratio, best) in module.gaps_of(hosts, None).items():
    gaps.append({"row": row, "host": host, "ratio": ratio, "best": best})
    if row not in labels:
        labels[row] = module.label(row)
print(
    json.dumps(
        {
            "files": files,
            "gaps": gaps,
            "columns": module.COLUMNS,
            "labels": labels,
        }
    )
)
"#;

fn call_report(
    rind: &Path,
    hosts: &Map<String, Value>,
    table: &Map<String, Value>,
    report: &Path,
    report_dir: &Path,
) -> Result<ReportOut, String> {
    let bench = rind.join("admin").join("bench-report");
    if !bench.is_file() {
        return Err(format!("render-side: no {}", bench.display()));
    }
    let mut req = Map::new();
    req.insert(
        "bench_report".into(),
        Value::String(bench.to_string_lossy().into_owned()),
    );
    req.insert("hosts".into(), Value::Object(hosts.clone()));
    req.insert("table".into(), Value::Object(table.clone()));
    req.insert(
        "report".into(),
        Value::String(report.to_string_lossy().into_owned()),
    );
    req.insert(
        "report_dir".into(),
        Value::String(report_dir.to_string_lossy().into_owned()),
    );
    let mut child = Command::new("python3")
        .arg("-c")
        .arg(DRIVER)
        .stdin(std::process::Stdio::piped())
        .stdout(std::process::Stdio::piped())
        .stderr(std::process::Stdio::piped())
        .spawn()
        .map_err(|err| format!("render-side: python3: {err}"))?;
    {
        let mut stdin = child
            .stdin
            .take()
            .ok_or_else(|| "render-side: python3 stdin".to_string())?;
        serde_json::to_writer(&mut stdin, &Value::Object(req))
            .map_err(|err| format!("render-side: python3 stdin: {err}"))?;
    }
    let out = child
        .wait_with_output()
        .map_err(|err| format!("render-side: python3: {err}"))?;
    if !out.status.success() {
        let err = String::from_utf8_lossy(&out.stderr);
        let err = err.trim();
        if err.is_empty() {
            return Err("render-side: python3 driver failed".into());
        }
        return Err(err.to_string());
    }
    let value: Value = serde_json::from_slice(&out.stdout)
        .map_err(|err| format!("render-side: python3 driver was not JSON: {err}"))?;
    parse_report_out(&value)
}

fn parse_report_out(value: &Value) -> Result<ReportOut, String> {
    let obj = value
        .as_object()
        .ok_or_else(|| "render-side: driver output must be an object".to_string())?;
    let files_obj = obj
        .get("files")
        .and_then(Value::as_object)
        .ok_or_else(|| "render-side: driver files must be an object".to_string())?;
    let mut files = Vec::new();
    for (path, content) in files_obj {
        let content = content
            .as_str()
            .ok_or_else(|| "render-side: report() file content must be a string".to_string())?;
        files.push((PathBuf::from(path), content.to_string()));
    }
    let mut gaps = Vec::new();
    let gaps_val = obj
        .get("gaps")
        .and_then(Value::as_array)
        .ok_or_else(|| "render-side: driver gaps must be an array".to_string())?;
    for gap in gaps_val {
        let g = gap
            .as_object()
            .ok_or_else(|| "render-side: gap must be an object".to_string())?;
        gaps.push(Gap {
            row: str_field(g, "row")?,
            host: str_field(g, "host")?,
            ratio: g
                .get("ratio")
                .and_then(Value::as_f64)
                .ok_or_else(|| "render-side: gap.ratio must be a number".to_string())?,
            best: str_field(g, "best")?,
        });
    }
    let columns = obj
        .get("columns")
        .and_then(Value::as_object)
        .cloned()
        .ok_or_else(|| "render-side: driver columns must be an object".to_string())?;
    let labels = obj
        .get("labels")
        .and_then(Value::as_object)
        .cloned()
        .ok_or_else(|| "render-side: driver labels must be an object".to_string())?;
    Ok(ReportOut {
        files,
        gaps,
        columns,
        labels,
    })
}

fn str_field(obj: &Map<String, Value>, key: &str) -> Result<String, String> {
    obj.get(key)
        .and_then(Value::as_str)
        .map(str::to_string)
        .ok_or_else(|| format!("render-side: gap.{key} must be a string"))
}

fn outside(rind: &Path, path: &Path) -> bool {
    path != rind && !path.starts_with(rind)
}

/// Python `Path.resolve(strict=False)`: absolute, follow existing symlinks.
pub fn resolve_path(path: &Path) -> Result<PathBuf, String> {
    let abs = if path.is_absolute() {
        path.to_path_buf()
    } else {
        std::env::current_dir()
            .map_err(|err| format!("render-side: {err}"))?
            .join(path)
    };
    let mut prefix = PathBuf::new();
    let mut rest = Vec::new();
    let mut saw_missing = false;
    for c in abs.components() {
        if saw_missing {
            rest.push(c.as_os_str().to_os_string());
            continue;
        }
        match c {
            Component::Prefix(_) | Component::RootDir => prefix.push(c),
            Component::CurDir => {}
            Component::ParentDir => {
                prefix.pop();
            }
            Component::Normal(s) => {
                prefix.push(s);
                if !prefix.exists() {
                    prefix.pop();
                    rest.push(s.to_os_string());
                    saw_missing = true;
                }
            }
        }
    }
    let mut resolved = if prefix.as_os_str().is_empty() {
        prefix
    } else if prefix.exists() {
        prefix
            .canonicalize()
            .map_err(|err| format!("render-side: {}: {err}", prefix.display()))?
    } else {
        prefix
    };
    for s in rest {
        resolved.push(s);
    }
    Ok(resolved)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn format_ratio_has_two_decimals() {
        assert_eq!(format_ratio(2.5), "2.50");
        assert_eq!(format_ratio(1.25), "1.25");
        assert_eq!(format_ratio(1.11), "1.11");
    }

    #[test]
    fn outside_rejects_a_path_under_rind() {
        let rind = PathBuf::from("/tmp/rind");
        assert!(!outside(&rind, Path::new("/tmp/rind")));
        assert!(!outside(&rind, Path::new("/tmp/rind/inside")));
        assert!(outside(&rind, Path::new("/tmp/out")));
    }
}
