//! `cargo xtask render-ours`: the side report for this repository's own hosts
//! (xeon-vm, m1pro, pi5, pixel9pro), drawn with rind's `admin/bench-report`
//! so the tables, SVGs, colours and thresholds are rind's. Ported from
//! `scripts/render-ours.py`, with the same output:
//!
//! - `OUT/STATS.md`, rind's report for these hosts, with rind's CPU tiers
//!   and known gaps replaced by this set's own gap list;
//! - `OUT/benchmarks/*.svg`, plus `overview-all{,-dark}.svg` with the six
//!   hosts upstream publishes beside these four;
//! - `OUT/summary.json`, every host's times, fastest library and standing.
//!
//! Host JSON is read from `RES/<file>/<file>.json`, where `<file>` is `box`
//! for xeon-vm (the script's names), and from `RIND/benchmarks/data/`.
//! Only `admin/bench-report`'s own functions run in Python (`report`,
//! `gaps_of`, `overview_svg`, `label`). Loading, the gap table, the summary
//! and the output files are here.

use crate::py;
use serde_json::{Map, Value};
use std::fs;
use std::io::Write;
use std::path::PathBuf;
use std::process::{Command, Stdio};

#[derive(clap::Args)]
pub struct Args {
    /// rind checkout whose admin/bench-report draws the report
    #[arg(long)]
    rind: PathBuf,
    /// directory holding <file>/<file>.json per host
    #[arg(long, env = "RES")]
    res: PathBuf,
    /// output directory, removed first [default: RES/render]
    #[arg(long, env = "OUT")]
    out: Option<PathBuf>,
}

/// The script's `FILES`: each host's JSON file name, where it is not the host's.
const FILES: &[(&str, &str)] = &[
    ("xeon-vm", "box"),
    ("m1pro", "m1pro"),
    ("pi5", "pi5"),
    ("pixel9pro", "pixel9pro"),
];

/// The script's `OURS`: the hosts and the note each one's section carries.
const OURS: &[(&str, &str)] = &[
    (
        "xeon-vm",
        "Cloud VM: 8 vCPUs, shared with other agents, so other work ran during the benchmarks; treat small differences as noise.",
    ),
    (
        "m1pro",
        "A MacBook Pro (M1 Pro), in daily use during the run. Its cores have DIT, which rind sets around each call that handles a secret and the other libraries never set. Built with Homebrew's rustc, not the Nix-pinned toolchain.",
    ),
    (
        "pi5",
        "Raspberry Pi 5 Model B (4× Cortex-A76), reached over ssh through the desktop; idle during the run. System OpenSSL headers unpacked locally, without installing anything.",
    ),
    (
        "pixel9pro",
        "Pixel 9 Pro (Google Tensor G4: 1× Cortex-X4, 3× A720, 4× A520), Android 17, charging, over adb from the desktop. The benches were cross-compiled on the box for aarch64-linux-android (NDK r28c, rustc 1.98.1) with OpenSSL vendored (openssl-src, static) since Android has no system OpenSSL, and run with the harness's criterion arguments and filter. Marked noisy: the scheduler could move the benchmark between core types, and the battery warmed from 24.7 to 37.7 °C. rind-bench times the DIT-held column only on Apple targets, so it is absent here. No build cost: nothing was built on the phone.",
    ),
];

/// The upstream hosts in `overview-all`, by data file.
const REPO: &[&str] = &["nixos", "desktop", "nixos2", "kixtop", "ovh-iad", "ovh-sea"];

const GENERATED: &str = "<!-- Generated by `admin/bench-report render` from benchmarks/data, benchmarks/verified.toml, and benchmarks/gaps.toml. -->";
const GENERATED_OURS: &str = "<!-- Generated by rind's own admin/bench-report renderer (report(), overview_svg(), host_svg()) from <results>/*.json. -->";
const PINNED: &str = "Each host builds with the pinned toolchain in the Nix dev shell, and runs `admin/bench-report` only when idle. Times are criterion's estimates.";
const PINNED_OURS: &str = "Each host ran `admin/bench-report run` (the host side of `collect`) through a small wrapper, `host-run.py`, that keeps its operations, criterion arguments, parsing, and JSON unchanged but records rather than refuses a busy host or a toolchain other than the Nix-pinned one. Times are criterion's estimates. A host marked noisy had other work busy during its run.";
const GAPS_INTRO: &str = "Each operation where another library is more than 10% faster than rind on one of these hosts, computed as `admin/bench-report` computes gaps. These are measurements only; the repo's `benchmarks/gaps.toml` holds the maintainers' decisions for its own hosts.";

/// Runs `admin/bench-report`'s renderers on the hosts it is given, in the
/// order the script called them, and returns their results as JSON.
const DRIVER: &str = r#"
import importlib.machinery, importlib.util, json, sys

req = json.load(sys.stdin)
loader = importlib.machinery.SourceFileLoader("br", req["bench_report"])
spec = importlib.util.spec_from_loader("br", loader)
br = importlib.util.module_from_spec(spec)
loader.exec_module(br)
needed = ("report", "load_verified", "gaps_of", "label", "row_name", "overview_svg",
          "COLUMNS", "OPERATIONS", "VARIANTS", "SLOWER", "HOSTS", "REPORT", "REPORT_DIR")
missing = [n for n in needed if not hasattr(br, n)]
if missing:
    sys.exit("render-ours: admin/bench-report is missing " + ", ".join(missing))
verified = br.load_verified()
ours, repo = req["ours"], req["repo"]
br.HOSTS = req["table"]
br.REPORT_DIR = req["report_dir"]
br.REPORT = req["report"]
files = br.report(ours, None, verified, None)
gaps = [[br.label(row), host, ratio, best]
        for (row, host), (ratio, best) in br.gaps_of(ours, None).items()]
allh = {**repo, **ours}
br.HOSTS = {n: {} for n in allh}
overview = {theme: br.overview_svg(allh, verified, theme) for theme in ("light", "dark")}
labels = {}
for h in allh.values():
    for r in h["results"]:
        row = br.row_name(r["operation"])
        if row not in labels:
            labels[row] = br.label(row)
print(json.dumps({
    "files": files, "gaps": gaps, "overview": overview, "labels": labels,
    "columns": br.COLUMNS, "order": [br.row_name(o) for o in br.OPERATIONS],
    "variants": list(br.VARIANTS), "slower": br.SLOWER, "hosts": allh,
}))
"#;

/// A host's JSON, if it exists and its status is ok. Others are reported
/// on stderr and left out, as the script did.
fn load(names: &[String], dir: &str, is_res: bool) -> Result<Map<String, Value>, String> {
    let mut hosts = Map::new();
    for n in names {
        let f = FILES
            .iter()
            .find(|(h, _)| h == n)
            .map_or(n.as_str(), |(_, f)| f);
        let p = if is_res {
            pjoin(&pjoin(dir, f), &format!("{f}.json"))
        } else {
            pjoin(dir, &format!("{n}.json"))
        };
        if !std::path::Path::new(&p).exists() {
            continue;
        }
        let h = crate::read_json(std::path::Path::new(&p))?;
        if h.get("status").and_then(Value::as_str) == Some("ok") {
            let mut h = match h {
                Value::Object(m) => m,
                _ => return Err(format!("{p}: not an object")),
            };
            h.insert("host".into(), Value::String(n.clone()));
            hosts.insert(n.clone(), Value::Object(h));
        } else {
            eprintln!(
                "skip {n}: {}: {}",
                py_str(h.get("status")),
                py_str(h.get("reason"))
            );
        }
    }
    Ok(hosts)
}

/// `os.path.join(a, b)` for a relative `b`.
fn pjoin(a: &str, b: &str) -> String {
    if a.is_empty() || a.ends_with('/') {
        format!("{a}{b}")
    } else {
        format!("{a}/{b}")
    }
}

/// `str(x)` of a JSON value as Python holds it.
fn py_str(v: Option<&Value>) -> String {
    match v {
        None | Some(Value::Null) => "None".into(),
        Some(Value::Bool(b)) => if *b { "True" } else { "False" }.into(),
        Some(Value::String(s)) => s.clone(),
        Some(Value::Number(n)) if n.is_f64() => py::repr(n.as_f64().unwrap_or(f64::NAN)),
        Some(Value::Number(n)) => n.to_string(),
        Some(other) => other.to_string(),
    }
}

/// `repr(str)`.
fn py_repr(s: &str) -> String {
    let q = if s.contains('\'') && !s.contains('"') {
        '"'
    } else {
        '\''
    };
    let mut out = String::from(q);
    for c in s.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if c == q => {
                out.push('\\');
                out.push(c);
            }
            c if (c as u32) < 0x20 || c as u32 == 0x7f => {
                out.push_str(&format!("\\x{:02x}", c as u32));
            }
            c => out.push(c),
        }
    }
    out.push(q);
    out
}

/// `print(list(d))` without the `print`.
fn py_list(keys: &[String]) -> String {
    let items: Vec<String> = keys.iter().map(|k| py_repr(k)).collect();
    format!("[{}]", items.join(", "))
}

fn run_driver(req: &Value) -> Result<Map<String, Value>, String> {
    let mut child = Command::new("python3")
        .arg("-c")
        .arg(DRIVER)
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::inherit())
        .spawn()
        .map_err(|e| format!("render-ours: python3: {e}"))?;
    child
        .stdin
        .take()
        .ok_or("render-ours: python3 stdin")?
        .write_all(py::dumps(req, None).as_bytes())
        .map_err(|e| format!("render-ours: python3 stdin: {e}"))?;
    let out = child
        .wait_with_output()
        .map_err(|e| format!("render-ours: python3: {e}"))?;
    if !out.status.success() {
        return Err("render-ours: admin/bench-report failed".into());
    }
    match serde_json::from_slice(&out.stdout) {
        Ok(Value::Object(m)) => Ok(m),
        Ok(_) => Err("render-ours: driver output is not an object".into()),
        Err(e) => Err(format!("render-ours: driver output is not JSON: {e}")),
    }
}

/// `str.partition(sep)`.
fn partition<'a>(s: &'a str, sep: &str) -> (&'a str, &'a str) {
    s.split_once(sep).unwrap_or((s, ""))
}

fn num(v: &Value) -> f64 {
    v.as_f64().unwrap_or(f64::NAN)
}

/// `times(host)`: each row's time by library, in first-seen order.
fn times(h: &Value) -> Result<Map<String, Value>, String> {
    let mut out = Map::new();
    for r in h["results"].as_array().ok_or("results is not a list")? {
        let op = r["operation"].as_str().ok_or("operation is not a string")?;
        let lib = r["library"].as_str().ok_or("library is not a string")?;
        let row = op.replace("/{lib}", "");
        let e = out.entry(row).or_insert_with(|| Value::Object(Map::new()));
        e.as_object_mut()
            .expect("row is an object")
            .insert(lib.to_string(), r["ns"].clone());
    }
    Ok(out)
}

/// `fastest(libs)`: the first library with the least time, variants aside.
fn fastest<'a>(libs: &'a Map<String, Value>, variants: &[String]) -> Result<&'a str, String> {
    let mut best: Option<(&str, f64)> = None;
    for (lib, ns) in libs {
        if variants.contains(lib) {
            continue;
        }
        let ns = num(ns);
        if best.is_none_or(|(_, b)| ns < b) {
            best = Some((lib, ns));
        }
    }
    best.map(|(l, _)| l)
        .ok_or_else(|| "ValueError: min() iterable argument is empty".into())
}

pub fn run(a: Args) -> Result<(), String> {
    let rind = a.rind.to_string_lossy().into_owned();
    let res = a.res.to_string_lossy().into_owned();
    let out = a.out.map_or_else(
        || pjoin(&res, "render"),
        |o| o.to_string_lossy().into_owned(),
    );
    let _ = fs::remove_dir_all(&out);
    let data = format!("{rind}/benchmarks/data");
    let our_names: Vec<String> = OURS.iter().map(|(n, _)| n.to_string()).collect();
    let ours = load(&our_names, &res, true)?;
    let mut repo_names = vec![];
    for n in REPO {
        let p = PathBuf::from(format!("{data}/{n}.json"));
        let h = crate::read_json(&p)?;
        repo_names.push(
            h["host"]
                .as_str()
                .ok_or_else(|| format!("{}: host is not a string", p.display()))?
                .to_string(),
        );
    }
    let repo = load(&repo_names, &data, res == data)?;
    let report_dir = pjoin(&out, "benchmarks");
    let report = pjoin(&out, "STATS.md");
    let mut table = Map::new();
    for (n, note) in OURS {
        let mut m = Map::new();
        m.insert("note".into(), Value::from(*note));
        table.insert(n.to_string(), Value::Object(m));
    }
    let mut req = Map::new();
    req.insert(
        "bench_report".into(),
        Value::from(format!("{rind}/admin/bench-report")),
    );
    req.insert("ours".into(), Value::Object(ours.clone()));
    req.insert("repo".into(), Value::Object(repo.clone()));
    req.insert("table".into(), Value::Object(table));
    req.insert("report_dir".into(), Value::from(report_dir.clone()));
    req.insert("report".into(), Value::from(report.clone()));
    let got = run_driver(&Value::Object(req))?;
    let field = |k: &str| {
        got.get(k)
            .ok_or_else(|| format!("render-ours: driver gave no {k}"))
    };

    // STATS.md: the script's two text swaps, then this set's gaps in place
    // of rind's CPU tiers and known gaps.
    let mut files = field("files")?
        .as_object()
        .ok_or("files is not an object")?
        .clone();
    let md = files
        .get(&report)
        .and_then(Value::as_str)
        .ok_or("render-ours: report() wrote no STATS.md")?
        .replace(GENERATED, GENERATED_OURS)
        .replace(PINNED, PINNED_OURS);
    let (head, rest) = partition(&md, "## CPU tiers");
    let (_, verified_part) = partition(rest, "## Verified code");
    let mut lines: Vec<String> = vec![
        "## Gaps on these hosts".into(),
        String::new(),
        GAPS_INTRO.into(),
        String::new(),
    ];
    let columns = field("columns")?.as_object().ok_or("columns")?.clone();
    let mut gaps: Vec<(usize, f64, String)> = vec![];
    for g in field("gaps")?.as_array().ok_or("gaps")? {
        let (label, host, ratio, best) = (
            g[0].as_str().unwrap_or_default(),
            g[1].as_str().unwrap_or_default(),
            num(&g[2]),
            g[3].as_str().unwrap_or_default(),
        );
        let idx = OURS
            .iter()
            .position(|(n, _)| *n == host)
            .ok_or_else(|| format!("ValueError: {} is not in list", py_repr(host)))?;
        let col = columns
            .get(best)
            .and_then(Value::as_str)
            .ok_or_else(|| format!("KeyError: {}", py_repr(best)))?;
        gaps.push((
            idx,
            ratio,
            format!("| {label} | `{host}` | {ratio:.2}× ({col}) |"),
        ));
    }
    if gaps.is_empty() {
        lines.push("None.".into());
    } else {
        lines.push("| Operation | On | rind's time over the fastest |".into());
        lines.push("|---|---|---|".into());
        // sorted(key=(host index, -ratio)), stable.
        gaps.sort_by(|a, b| a.0.cmp(&b.0).then(b.1.total_cmp(&a.1)));
        lines.extend(gaps.into_iter().map(|g| g.2));
    }
    let md = format!(
        "{head}{}\n\n## Verified code{verified_part}",
        lines.join("\n")
    );
    files.insert(report.clone(), Value::String(md));
    fs::create_dir_all(&report_dir).map_err(|e| format!("{report_dir}: {e}"))?;
    let write = |p: &str, c: &str| fs::write(p, c).map_err(|e| format!("{p}: {e}"));
    for (p, c) in &files {
        write(p, c.as_str().ok_or("a report file is not text")?)?;
    }

    let overview = field("overview")?;
    for (theme, suf) in [("light", ""), ("dark", "-dark")] {
        let svg = overview[theme].as_str().ok_or("overview")?;
        write(&pjoin(&report_dir, &format!("overview-all{suf}.svg")), svg)?;
    }

    // summary.json, from the hosts as bench-report left them.
    let allh = field("hosts")?.as_object().ok_or("hosts")?;
    let labels = field("labels")?.as_object().ok_or("labels")?;
    let variants: Vec<String> = field("variants")?
        .as_array()
        .ok_or("variants")?
        .iter()
        .filter_map(|v| v.as_str().map(str::to_string))
        .collect();
    let slower = num(field("slower")?);
    let mut summ = Map::new();
    let mut standings = vec![];
    for (n, h) in allh {
        let t = times(h)?;
        let (mut lead, mut timed) = (0i64, 0i64);
        let mut rows = Map::new();
        for (row, libs) in &t {
            let libs = libs.as_object().expect("row is an object");
            if libs.contains_key("rind")
                && libs.keys().any(|l| l != "rind" && !variants.contains(l))
            {
                let r = num(&libs["rind"]) / num(&libs[fastest(libs, &variants)?]);
                timed += 1;
                lead += i64::from(r <= slower);
            }
            let mut e = Map::new();
            e.insert(
                "label".into(),
                labels
                    .get(row)
                    .cloned()
                    .ok_or_else(|| format!("KeyError: {}", py_repr(row)))?,
            );
            e.insert("times".into(), Value::Object(libs.clone()));
            e.insert("fastest".into(), Value::from(fastest(libs, &variants)?));
            rows.insert(row.clone(), Value::Object(e));
        }
        let get = |k: &str| h.get(k).cloned().unwrap_or(Value::Null);
        let need = |k: &str| {
            h.get(k)
                .cloned()
                .ok_or_else(|| format!("KeyError: {}", py_repr(k)))
        };
        let mut s = Map::new();
        let source = if repo.contains_key(n) {
            "BENCHMARKS.md/benchmarks/data"
        } else {
            "this run"
        };
        s.insert("source".into(), Value::from(source));
        s.insert("cpu".into(), need("cpu")?);
        s.insert("os".into(), need("os")?);
        s.insert(
            "rustc".into(),
            need("toolchain")?
                .get("rustc")
                .cloned()
                .ok_or("KeyError: 'rustc'")?,
        );
        s.insert("commit".into(), need("commit")?);
        s.insert("started".into(), need("started")?);
        s.insert("load".into(), get("load"));
        s.insert("refused".into(), get("refused"));
        s.insert("lead".into(), Value::from(lead));
        s.insert("timed".into(), Value::from(timed));
        s.insert("rows".into(), Value::Object(rows));
        s.insert("build_cost".into(), get("build_cost"));
        summ.insert(n.clone(), Value::Object(s));
        standings.push(format!("{n} {lead} / {timed}"));
    }
    let mut top = Map::new();
    top.insert("order".into(), field("order")?.clone());
    top.insert("columns".into(), Value::Object(columns));
    top.insert("hosts".into(), Value::Object(summ));
    write(
        &format!("{out}/summary.json"),
        &py::dumps(&Value::Object(top), Some(1)),
    )?;
    let ours_keys: Vec<String> = ours.keys().cloned().collect();
    let repo_keys: Vec<String> = repo.keys().cloned().collect();
    println!(
        "ours: {} repo: {}",
        py_list(&ours_keys),
        py_list(&repo_keys)
    );
    for s in standings {
        println!("{s}");
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn repr_quotes_like_python() {
        assert_eq!(py_repr("pi5"), "'pi5'");
        assert_eq!(py_repr("it's"), "\"it's\"");
        assert_eq!(py_repr("a'\"b"), "'a\\'\"b'");
        assert_eq!(py_list(&["a".into(), "b".into()]), "['a', 'b']");
        assert_eq!(py_list(&[]), "[]");
    }

    #[test]
    fn partition_like_python() {
        assert_eq!(partition("a## Xb", "## X"), ("a", "b"));
        assert_eq!(partition("ab", "## X"), ("ab", ""));
    }
}
