#!/usr/bin/env python3
"""Renders our hosts' results with rind's own admin/bench-report renderer
(same tables, SVGs, colors, thresholds), into <results>/render.
Does not touch the checkout's BENCHMARKS.md or benchmarks/."""
import importlib.machinery, importlib.util, json, os, re, sys
RIND = "<rind>"; RES = os.environ.get("RES", "<results>"); OUT = os.environ.get("OUT", f"{RES}/render")
loader = importlib.machinery.SourceFileLoader("br", f"{RIND}/admin/bench-report")
spec = importlib.util.spec_from_loader("br", loader); br = importlib.util.module_from_spec(spec); loader.exec_module(br)

FILES = {"xeon-vm": "box", "m1pro": "m1pro", "pi5": "pi5", "pixel9pro": "pixel9pro"}
OURS = {
    "xeon-vm": {"note": "Cloud VM: 8 vCPUs, shared with other agents, so other work ran during the benchmarks; treat small differences as noise."},
    "m1pro": {"note": "A MacBook Pro (M1 Pro), in daily use during the run. Its cores have DIT, which rind sets around each call that handles a secret and the other libraries never set. Built with Homebrew's rustc, not the Nix-pinned toolchain."},
    "pi5": {"note": "Raspberry Pi 5 Model B (4× Cortex-A76), reached over ssh through the desktop; idle during the run. System OpenSSL headers unpacked locally, without installing anything."},
    "pixel9pro": {"note": "Pixel 9 Pro (Google Tensor G4: 1× Cortex-X4, 3× A720, 4× A520), Android 17, charging, over adb from the desktop. The benches were cross-compiled on the box for aarch64-linux-android (NDK r28c, rustc 1.98.1) with OpenSSL vendored (openssl-src, static) since Android has no system OpenSSL, and run with the harness's criterion arguments and filter. Marked noisy: the scheduler could move the benchmark between core types, and the battery warmed from 24.7 to 37.7 °C. rind-bench times the DIT-held column only on Apple targets, so it is absent here. No build cost: nothing was built on the phone."},
}
def load(names, d):
    hosts = {}
    for n in names:
        f = FILES.get(n, n)
        p = os.path.join(d, f, f"{f}.json") if d == RES else os.path.join(d, f"{n}.json")
        if os.path.exists(p):
            h = json.load(open(p))
            if h.get("status") == "ok": h = dict(h, host=n); hosts[n] = h
            else: print(f"skip {n}: {h.get('status')}: {h.get('reason')}", file=sys.stderr)
    return hosts

verified = br.load_verified()
import shutil; shutil.rmtree(OUT, ignore_errors=True)
ours = load(OURS, RES)
br.HOSTS = OURS
br.REPORT_DIR = os.path.join(OUT, "benchmarks"); br.REPORT = os.path.join(OUT, "STATS.md")
files = br.report(ours, None, verified, None)
md = files[br.REPORT]
md = md.replace("<!-- Generated by `admin/bench-report render` from benchmarks/data, benchmarks/verified.toml, and benchmarks/gaps.toml. -->",
  "<!-- Generated by rind's own admin/bench-report renderer (report(), overview_svg(), host_svg()) from <results>/*.json. -->")
md = md.replace("Each host builds with the pinned toolchain in the Nix dev shell, and runs `admin/bench-report` only when idle. Times are criterion's estimates.",
  "Each host ran `admin/bench-report run` (the host side of `collect`) through a small wrapper, `host-run.py`, that keeps its operations, criterion arguments, parsing, and JSON unchanged but records rather than refuses a busy host or a toolchain other than the Nix-pinned one. Times are criterion's estimates. A host marked noisy had other work busy during its run.")
# Replace CPU tiers + Known gaps with our gap list.
head, _, rest = md.partition("## CPU tiers")
_, _, verified_part = rest.partition("## Verified code")
gaps = br.gaps_of(ours, None)
lines = ["## Gaps on these hosts", "",
  "Each operation where another library is more than 10% faster than rind on one of these hosts, computed as `admin/bench-report` computes gaps. These are measurements only; the repo's `benchmarks/gaps.toml` holds the maintainers' decisions for its own hosts.", ""]
if gaps:
    lines += ["| Operation | On | rind's time over the fastest |", "|---|---|---|"]
    for (row, host), (ratio, best) in sorted(gaps.items(), key=lambda kv: (list(OURS).index(kv[0][1]), -kv[1][0])):
        lines.append(f"| {br.label(row)} | `{host}` | {ratio:.2f}× ({br.COLUMNS[best]}) |")
else:
    lines.append("None.")
md = head + "\n".join(lines) + "\n\n## Verified code" + verified_part
files[br.REPORT] = md
os.makedirs(br.REPORT_DIR, exist_ok=True)
for p, c in files.items():
    open(p, "w").write(c)

# Combined overview: the repo's six published hosts plus ours.
repo = load(list(json.load(open(f"{RIND}/benchmarks/data/{n}.json"))["host"] for n in ["nixos","desktop","nixos2","kixtop","ovh-iad","ovh-sea"]), f"{RIND}/benchmarks/data")
allh = {**repo, **ours}
br.HOSTS = {n: {} for n in allh}
for theme, suf in (("light", ""), ("dark", "-dark")):
    open(os.path.join(br.REPORT_DIR, f"overview-all{suf}.svg"), "w").write(br.overview_svg(allh, verified, theme))
# Summary JSON for the Page.
summ = {}
for n, h in allh.items():
    t = br.times(h); lead, timed = br.standing({n: h})
    rows = {}
    for row, libs in t.items():
        f = br.fastest(libs)
        rows[row] = {"label": br.label(row), "times": libs, "fastest": f}
    summ[n] = {"source": "BENCHMARKS.md/benchmarks/data" if n in repo else "this run", "cpu": h["cpu"], "os": h["os"],
               "rustc": h["toolchain"]["rustc"], "commit": h["commit"], "started": h["started"], "load": h.get("load"),
               "refused": h.get("refused"), "lead": lead, "timed": timed, "rows": rows, "build_cost": h.get("build_cost")}
json.dump({"order": [br.row_name(o) for o in br.OPERATIONS], "columns": br.COLUMNS, "hosts": summ}, open(f"{OUT}/summary.json", "w"), indent=1)
print("ours:", list(ours), "repo:", list(repo))
for n in allh: print(n, summ[n]["lead"], "/", summ[n]["timed"])
