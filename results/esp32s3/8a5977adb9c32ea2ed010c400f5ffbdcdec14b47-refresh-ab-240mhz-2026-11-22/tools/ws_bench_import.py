"""Turn interleaved WS-BENCH serial logs into a result tree.

usage: python3 -I tools/ws_bench_import.py tools/import.json   (run from the tree)

Reads only the tree's own files: the config (tools/import.json) and the serial
logs it names under raw/. Writes:

  raw/run-<k>.json   one per control flash, schema 1 (the control's runs)
  <host>.json        schema 1, the median of the control runs
  RUNS.md            every control run, the median and the spread
  RESULTS.md         rind against the fastest other library, for the control
  ab.json, ab.md     rind-results/ab-v1: every flash of every image

A log is one flash (one boot). Rows are `WS-BENCH v1 <op> lib=<lib> chip=<chip>
median_ns=<N> iters=<I> bytes=<B>`, printed once per round; each value is the
firmware's median of I calls. Rows before the first `# round complete` are
dropped (the capture opens part way into the first round). A flash's estimate
for a row is the median over its remaining rounds. A run is one flash.
"""

import json
import os
import re
import statistics
import sys

ROW = re.compile(
    r"^WS-BENCH v1 (\S+) lib=(\S+) chip=(\S+) median_ns=(\d+) iters=(\d+) bytes=(\d+)\s*$"
)
KAT = re.compile(r"^WS-KAT v1 (\S+) lib=(\S+) result=(\S+)\s*$")
MARK = "# round complete"
COLUMNS = [
    ("rind", "rind"),
    ("aws-lc-rs", "aws-lc-rs"),
    ("ring", "ring"),
    ("rustcrypto", "RustCrypto + dalek"),
    ("graviola", "graviola"),
    ("libcrux", "libcrux"),
    ("openssl", "OpenSSL"),
]
SPDX = "<!-- SPDX-License-Identifier: Apache-2.0 OR ISC OR MIT-0 -->"
GEN = "<!-- Generated by tools/ws_bench_import.py from raw/ and tools/import.json; edit those, not this. -->"


def heading(lib):
    return dict(COLUMNS).get(lib, lib)


def human(ns):
    if ns < 1e3:
        return f"{ns:.0f} ns"
    if ns < 1e6:
        return f"{ns / 1e3:.2f} µs"
    return f"{ns / 1e6:.2f} ms"


def us(ns):
    return f"{ns / 1e3:.2f}"


def spread_med(xs):
    return (max(xs) - min(xs)) / statistics.median(xs) * 100.0


def spread_min(xs):
    lo = min(xs)
    return 0.0 if lo == 0 else (max(xs) - lo) / lo * 100.0


def op_id(op, nbytes):
    return f"{op}/{{lib}}/{nbytes}B"


def label(op):
    return op.replace("/{lib}", "")


def parse(path):
    text = open(path, "rb").read().decode("utf-8", "replace")
    lines = text.splitlines()
    marks = [i for i, l in enumerate(lines) if l.strip() == MARK]
    if not marks:
        raise SystemExit(f"{path}: no '{MARK}'")
    body = lines[marks[0] + 1 :]
    rows = {}
    order = []
    other = 0
    for l in body:
        m = ROW.match(l)
        if m:
            key = (op_id(m[1], int(m[6])), m[2])
            if key not in rows:
                rows[key] = {"rounds_ns": [], "iters": int(m[5]), "bytes": int(m[6]), "chip": m[3]}
                order.append(key)
            rows[key]["rounds_ns"].append(int(m[4]))
        elif l.strip() == MARK or KAT.match(l):
            pass
        elif l.strip():
            other += 1
    kats = {"pass": 0, "fail": 0}
    for l in lines:
        m = KAT.match(l)
        if m:
            kats["pass" if m[3] == "PASS" else "fail"] += 1
    failed_lines = len(re.findall(r"FAILED", text))
    return {
        "rows": rows,
        "order": order,
        "complete_rounds": len(marks) - 1,
        "kats": kats,
        "failed_lines": failed_lines,
        "other_lines": other,
    }


def fmt_pct(x, d):
    return f"{x:.{d}f}"


def main():
    cfg_path = sys.argv[1]
    cfg = json.load(open(cfg_path))
    host = cfg["host"]
    ctl = cfg["control"]
    flashes = []
    for f in cfg["flashes"]:
        p = parse(f["log"])
        if p["kats"]["fail"] or p["failed_lines"]:
            raise SystemExit(f"{f['log']}: failed known-answer checks")
        flashes.append((f, p))

    # Control runs.
    ctl_flashes = [(f, p) for f, p in flashes if f["variant"] == ctl]
    os.makedirs("raw", exist_ok=True)
    keys = []
    for _, p in ctl_flashes:
        for k in p["order"]:
            if k not in keys:
                keys.append(k)
    runs = []
    for k_i, (f, p) in enumerate(ctl_flashes, 1):
        results = []
        for key in keys:
            if key not in p["rows"]:
                raise SystemExit(f"{f['log']}: no {key}")
            r = p["rows"][key]
            op, lib = key
            results.append(
                {
                    "operation": op,
                    "library": lib,
                    "id": op.replace("{lib}", lib),
                    "ns": statistics.median(r["rounds_ns"]),
                    "rounds_ns": r["rounds_ns"],
                    "iters": r["iters"],
                    "throughput": {"Bytes": r["bytes"]},
                }
            )
        run = {
            "schema": 1,
            "host": host,
            "commit": cfg["commit"],
            "status": "ok",
            "run": k_i,
            "flash": f["n"],
            "variant": ctl,
            "image": cfg["variants"][ctl]["image"],
            "log": os.path.basename(f["log"]),
            "complete_rounds": p["complete_rounds"],
            "kats": p["kats"],
            "results": results,
        }
        if cfg.get("fork_commit"):
            run["fork_commit"] = cfg["fork_commit"]
        runs.append(run)
        with open(f"raw/run-{k_i}.json", "w") as o:
            json.dump(run, o, indent=1, ensure_ascii=False)
            o.write("\n")

    by = {}
    for key in keys:
        by[key] = [next(r["ns"] for r in run["results"] if (r["operation"], r["library"]) == key) for run in runs]

    # <host>.json
    out = {
        "schema": 1,
        "host": host,
        "commit": cfg["commit"],
        "upstream_commit": cfg["commit"],
    }
    if cfg.get("fork_commit"):
        out["fork_commit"] = cfg["fork_commit"]
    out.update(
        {
            "started": cfg["started"],
            "finished": cfg["finished"],
            "cpu": cfg["cpu"],
            "os": cfg["os"],
            "toolchain": cfg["toolchain"],
            "status": "ok",
            "board": cfg["board"],
            "clock_hz": cfg["clock_hz"],
            "harness": cfg["harness"],
            "runs": len(runs),
            "spread_is": "runs",
            "metric_units": "ns",
            "note": cfg["note"],
            "results": [],
        }
    )
    for key in keys:
        op, lib = key
        xs = by[key]
        r0 = runs[0]["results"][keys.index(key)]
        out["results"].append(
            {
                "operation": op,
                "library": lib,
                "id": op.replace("{lib}", lib),
                "ns": statistics.median(xs),
                "ns_low": min(xs),
                "ns_high": max(xs),
                "runs_ns": xs,
                "run_spread_pct": spread_med(xs),
                "iters": r0["iters"],
                "throughput": r0["throughput"],
            }
        )
    with open(f"{host}.json", "w") as o:
        json.dump(out, o, indent=1, ensure_ascii=False)
        o.write("\n")

    ops = []
    for op, _ in keys:
        if op not in ops:
            ops.append(op)

    # RUNS.md
    w = [SPDX, GEN, f"# `{host}` control (`{ctl}`): every run", ""]
    w.append(
        f"A run is one flash of the control image `{cfg['variants'][ctl]['image']}`. Each run's value is the median "
        "over that boot's complete rounds of the firmware's printed median; the median of the runs is published in "
        f"`{host}.json` and RESULTS.md. Spread is (slowest − fastest run) / median."
    )
    w.append("")
    w.append("| Operation | Library | " + " | ".join(f"run-{i} (flash {f['n']})" for i, (f, _) in enumerate(ctl_flashes, 1)) + " | Median | Spread |")
    w.append("|---|---|" + "---|" * len(runs) + "---|---|")
    for key in keys:
        op, lib = key
        xs = by[key]
        w.append(
            f"| {label(op)} | {heading(lib)} | "
            + " | ".join(human(x) for x in xs)
            + f" | {human(statistics.median(xs))} | {fmt_pct(spread_med(xs), 1)}% |"
        )
    open("RUNS.md", "w").write("\n".join(w) + "\n")

    # ab.json
    ab = {
        "schema": "rind-results/ab-v1",
        "host": host,
        "chip": cfg["chip"],
        "board": cfg["board"],
        "clock_hz": cfg["clock_hz"],
        "commit": cfg["commit"],
        "control": ctl,
        "order": [f"{f['n']} {f['variant']}" for f, _ in flashes],
        "modes": {v: d for v, d in cfg["variants"].items()},
        "method": (
            "Interleaved A/B. One flash = one boot = one run. A run's value for a row is the median over that "
            "boot's complete rounds (rows before the first '# round complete' dropped) of the firmware's printed "
            "median_ns. Each result here is one flash."
        ),
        "results": [],
    }
    for f, p in flashes:
        for key in p["order"]:
            op, lib = key
            r = p["rows"][key]
            ab["results"].append(
                {
                    "operation": op,
                    "library": lib,
                    "mode": f["variant"],
                    "flash": f["n"],
                    "ns": statistics.median(r["rounds_ns"]),
                    "rounds": len(r["rounds_ns"]),
                }
            )
    with open("ab.json", "w") as o:
        json.dump(ab, o, indent=1, ensure_ascii=False)
        o.write("\n")

    # ab.md
    modes = cfg["ab_order"]
    samples = {}
    for f, p in flashes:
        for key, r in p["rows"].items():
            samples.setdefault((key[0], key[1], f["variant"]), []).append(statistics.median(r["rounds_ns"]))
    counts = {v: sum(1 for f, _ in flashes if f["variant"] == v) for v in modes}
    a = [SPDX, GEN, f"# {cfg['title']}: every image", ""]
    a.append(
        "rind's time for each image, in µs: the median over that image's flashes, with the number of flashes (n) "
        "and the spread (slowest − fastest flash) / fastest. A ratio is the image's median over the control's "
        f"(`{ctl}`); below 1 is faster than the control. "
        + "; ".join(f"`{v}` was flashed {'once' if counts[v] == 1 else str(counts[v]) + ' times'}" for v in modes)
        + ". An image flashed once has one run, so its spread is 0 and says nothing about repeatability; "
        "read it against the control's spread. The RustCrypto column is the median of every flash of every image "
        "(the same RustCrypto code in each image, a layout control). Every number here is recomputed from "
        "[ab.json](ab.json) by `cargo verify`."
    )
    a.append("")

    def table(with_rc):
        sel = [op for op in ops if ((op, "rustcrypto") in by) == with_rc and (op, "rind") in by]
        if not sel:
            return
        hdr = ["op"]
        for v in modes:
            hdr.append(f"{v} µs (n, spread)")
            if v != ctl:
                hdr.append(f"{v}/{ctl}")
        if with_rc:
            hdr.append("rustcrypto µs")
            hdr.append(f"{ctl}/rustcrypto")
        a.append("| " + " | ".join(hdr) + " |")
        a.append("|" + "---|" * len(hdr))
        for op in sel:
            cells = [label(op)]
            base = samples.get((op, "rind", ctl))
            for v in modes:
                xs = samples.get((op, "rind", v))
                if xs:
                    cells.append(f"{us(statistics.median(xs))} ({len(xs)}, {fmt_pct(spread_min(xs), 2)}%)")
                else:
                    cells.append("–")
                if v != ctl:
                    if xs and base:
                        cells.append(f"{statistics.median(xs) / statistics.median(base):.4f}")
                    else:
                        cells.append("–")
            if with_rc:
                pooled = [x for (o, l, _), xs in samples.items() if o == op and l == "rustcrypto" for x in xs]
                cells.append(us(statistics.median(pooled)))
                cells.append(f"{statistics.median(base) / statistics.median(pooled):.4f}")
            a.append("| " + " | ".join(cells) + " |")
        a.append("")

    a.append("## Rows with a RustCrypto counterpart")
    a.append("")
    table(True)
    if any((op, "rustcrypto") not in by for op in ops):
        a.append("## rind-only rows")
        a.append("")
        table(False)

    # RustCrypto per image, for the layout control (not checked cell by cell: the verifier checks rind per mode).
    a.append("## Flashes")
    a.append("")
    a.append("| Flash | Image | Log | Complete rounds | Known-answer checks (pass, fail) | Other lines after round 1 |")
    a.append("|---:|---|---|---:|---|---:|")
    for f, p in flashes:
        a.append(
            f"| {f['n']} | `{f['variant']}` | [{os.path.basename(f['log'])}]({f['log']}) | {p['complete_rounds']} | "
            f"{p['kats']['pass']}, {p['kats']['fail']} | {p['other_lines']} |"
        )
    a.append("")
    open("ab.md", "w").write("\n".join(a) + "\n")

    # RESULTS.md
    r = [SPDX, GEN, f"# {cfg['title']}", ""]
    r.extend(cfg["results_intro"])
    r.append("")
    r.append(f"- Board: {cfg['board']}")
    r.append(f"- CPU: {cfg['cpu']['model']}")
    r.append(f"- Toolchain: {cfg['toolchain']['rustc']}")
    r.append(f"- Control image `{ctl}`: {cfg['variants'][ctl]['what']}")
    r.append(f"- Control runs: {len(runs)} flashes ({', '.join(str(f['n']) for f, _ in ctl_flashes)} of {len(flashes)})")
    r.append("")
    r.append("## rind against the fastest other library (control image)")
    r.append("")
    r.append(
        "Below 1.00× rind is faster. Spread is (slowest − fastest run) over the median, for rind and for the "
        "fastest other library. The only other library in this firmware is RustCrypto (ed25519-dalek for Ed25519)."
    )
    r.append("")
    r.append("| Operation | rind | Fastest other | rind / fastest | Spread (rind, other) |")
    r.append("|---|---|---|---|---|")
    wins = timed = 0
    for op in ops:
        if (op, "rind") not in by:
            continue
        rivals = [(l, by[(o, l)]) for (o, l) in keys if o == op and l != "rind" and not l.startswith("rind-")]
        if not rivals:
            continue
        bl, bx = rivals[0]
        for l, xs in rivals[1:]:
            if statistics.median(xs) < statistics.median(bx):
                bl, bx = l, xs
        rx = by[(op, "rind")]
        rm, bm = statistics.median(rx), statistics.median(bx)
        timed += 1
        wins += rm <= bm
        r.append(
            f"| {label(op)} | {human(rm)} | {heading(bl)}, {human(bm)} | {rm / bm:.2f}× | "
            f"{fmt_pct(spread_med(rx), 1)}%, {fmt_pct(spread_med(bx), 1)}% |"
        )
    r.append("")
    r.append(f"rind is the fastest on {wins} of {timed} operations it shares with another library.")
    r.append("")
    r.append("## Every library (control image)")
    r.append("")
    r.append("| Operation | " + " | ".join(h for _, h in COLUMNS) + " |")
    r.append("|---|" + "---|" * len(COLUMNS))
    for op in ops:
        cells = [human(statistics.median(by[(op, l)])) if (op, l) in by else "-" for l, _ in COLUMNS]
        r.append(f"| {label(op)} | " + " | ".join(cells) + " |")
    r.append("")
    r.append("## Images against the control")
    r.append("")
    r.extend(cfg["results_ab"])
    r.append("")
    open("RESULTS.md", "w").write("\n".join(r) + "\n")

    # meta.json: provenance.
    meta = {
        "schema": 1,
        "host": host,
        "commit": cfg["commit"],
        "upstream_commit": cfg["commit"],
    }
    if cfg.get("fork_commit"):
        meta["fork_commit"] = cfg["fork_commit"]
    meta.update(
        {
            "board": cfg["board"],
            "chip": cfg["chip"],
            "clock_hz": cfg["clock_hz"],
            "toolchain": cfg["toolchain"],
            "harness": cfg["harness"],
            "started": cfg["started"],
            "finished": cfg["finished"],
            "control": ctl,
            "runs": len(runs),
            "flashes": len(flashes),
            "images": {},
            "kats": {"checks": 0, "failures": 0, "boots": len(flashes)},
        }
    )
    for v, d in cfg["variants"].items():
        fl = [(f, p) for f, p in flashes if f["variant"] == v]
        e = dict(d)
        e["flashes"] = [f["n"] for f, _ in fl]
        e["kats_pass"] = sum(p["kats"]["pass"] for _, p in fl)
        e["kats_fail"] = sum(p["kats"]["fail"] for _, p in fl)
        meta["images"][v] = e
        meta["kats"]["checks"] += e["kats_pass"] + e["kats_fail"]
        meta["kats"]["failures"] += e["kats_fail"]
    with open("meta.json", "w") as o:
        json.dump(meta, o, indent=1, ensure_ascii=False)
        o.write("\n")
    print(f"{host}: {len(runs)} control runs, {len(keys)} rows, {len(flashes)} flashes, {wins} of {timed}")


if __name__ == "__main__":
    main()
