uint8_t kat_eq_p(const uint8_t *got, const uint8_t *src, uint16_t n) {
    for (uint16_t i = 0; i < n; i++) {
        if (got[i] != pgm_read_byte(&src[i])) return 0;
    }
    return 1;
}
uint8_t kat_eq_sha256_empty(const uint8_t *got) { return kat_eq_p(got, sha256_empty, 32); }
uint8_t kat_eq_sha256_abc(const uint8_t *got) { return kat_eq_p(got, sha256_abc, 32); }
uint8_t kat_eq_sha512_abc(const uint8_t *got) { return kat_eq_p(got, sha512_abc, 64); }
uint8_t kat_eq_chacha(const uint8_t *got) { return kat_eq_p(got, chacha_out, 114); }
uint8_t kat_eq_poly(const uint8_t *got) { return kat_eq_p(got, poly_tag, 16); }

static void load_p(uint8_t *dst, const uint8_t *src, uint16_t n) {
    for (uint16_t i = 0; i < n; i++) dst[i] = pgm_read_byte(&src[i]);
}
void kat_load_chacha_in(uint8_t *dst) { load_p(dst, chacha_in, 114); }
void kat_load_poly_key(uint8_t *dst) { load_p(dst, poly_key, 32); }
void kat_load_poly_msg(uint8_t *dst) { load_p(dst, poly_msg, 34); }
