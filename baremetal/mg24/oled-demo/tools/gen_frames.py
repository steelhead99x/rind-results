#!/usr/bin/env python3
"""Render the three 128x64 1-bit OLED frames.

The rind wordmark is vendored at ../vendor/wordmark-light.svg. The moq.dev
favicon is not redistributed; it is downloaded into ../assets/ only when its
SHA-256 matches the pin below. A mismatch exits before any frame is drawn.
Writes ../oled_demo/frames.h and ../preview*.png.
"""
import hashlib
import io
import os
import urllib.request

import cairosvg
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
A = os.path.join(HERE, "..", "assets")
OUT = os.path.join(HERE, "..")
WORDMARK = os.path.join(HERE, "..", "vendor", "wordmark-light.svg")
W, H = 128, 64
SANS_B = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
SANS = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"

# SHA-256 of the official SVG bytes.
WORDMARK_SHA256 = "8a16e64f1e13df5e03b2312315cfa6270443dc130e9ebcb973cb72f8afc96111"
FAVICON_SHA256 = "241bd5a8c3291315d7a617a4ac0c869c9cc5e4a34f6342ff91ae999c3d3dc8f1"
FAVICON_URL = "https://moq.dev/layout/favicon.svg"
FAVICON_NAME = "moqdev-layout_favicon.svg"


def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def require_digest(path, digest):
    if not os.path.isfile(path) or sha256_file(path) != digest:
        raise SystemExit(os.path.basename(path) + ": sha256 mismatch")


def ensure_favicon():
    os.makedirs(A, exist_ok=True)
    dest = os.path.join(A, FAVICON_NAME)
    if os.path.isfile(dest):
        if sha256_file(dest) != FAVICON_SHA256:
            os.remove(dest)
            raise SystemExit(FAVICON_NAME + ": sha256 mismatch")
        return dest
    tmp = dest + ".part"
    try:
        with urllib.request.urlopen(FAVICON_URL, timeout=60) as r:
            data = r.read()
        if hashlib.sha256(data).hexdigest() != FAVICON_SHA256:
            raise SystemExit(FAVICON_NAME + ": sha256 mismatch")
        with open(tmp, "wb") as f:
            f.write(data)
        os.replace(tmp, dest)
    finally:
        if os.path.exists(tmp):
            os.remove(tmp)
    return dest


def svg_rgba(path, px_w=None, px_h=None):
    png = cairosvg.svg2png(url=path, output_width=px_w, output_height=px_h)
    return Image.open(io.BytesIO(png)).convert("RGBA")

def to_bits(img, lit):
    out = Image.new("L", img.size, 0)
    px, op = img.load(), out.load()
    for y in range(img.size[1]):
        for x in range(img.size[0]):
            if lit(*px[x, y]):
                op[x, y] = 255
    return out

def downsample(mask, size, thr=110):
    small = mask.resize(size, Image.BOX)
    return small.point(lambda v: 255 if v >= thr else 0)

def text(d, xy, s, font, size):
    d.fontmode = "1"
    d.text(xy, s, fill=255, font=ImageFont.truetype(font, size))

def center_text(d, y, s, font, size, x0=0, x1=W):
    f = ImageFont.truetype(font, size)
    w = d.textlength(s, font=f)
    d.fontmode = "1"
    d.text((x0 + (x1 - x0 - w) // 2, y), s, fill=255, font=f)

require_digest(WORDMARK, WORDMARK_SHA256)
favicon = ensure_favicon()
frames = []

# 1. moq.dev mark (favicon; drop background: white letters + green arrow lit)
icon = svg_rgba(favicon, 512, 512)
lum = lambda r, g, b, a: a > 128 and (0.299 * r + 0.587 * g + 0.114 * b) > 90
mark = downsample(to_bits(icon, lum), (60, 60))
f1 = Image.new("L", (W, H), 0)
f1.paste(mark, (2, 2))
d = ImageDraw.Draw(f1)
center_text(d, 8, "moq.dev", SANS_B, 13, 64, 128)
center_text(d, 30, "Media over", SANS, 10, 64, 128)
center_text(d, 42, "QUIC", SANS_B, 10, 64, 128)
frames.append(("moq", f1))

# 2. rind wordmark (cream highlight left dark as a gap)
wm = svg_rgba(WORDMARK, 1000)
lum2 = lambda r, g, b, a: a > 128 and (0.299 * r + 0.587 * g + 0.114 * b) < 225
wmask = to_bits(wm, lum2)
wmask = wmask.crop(wmask.getbbox())
h = 48; w = round(wmask.size[0] * h / wmask.size[1])
wsmall = downsample(wmask, (w, h), 100)
f2 = Image.new("L", (W, H), 0)
f2.paste(wsmall, ((W - w) // 2, 1))
d = ImageDraw.Draw(f2)
center_text(d, 52, "pure-Rust crypto", SANS, 9)
frames.append(("rind", f2))

# 3. Benchmark headline (rind b6651423, TLS 1.3 full handshake, X25519)
f3 = Image.new("L", (W, H), 0)
d = ImageDraw.Draw(f3)
center_text(d, 0, "TLS 1.3 handshake", SANS_B, 9)
center_text(d, 10, "X25519, full", SANS, 9)
d.line((0, 21, 127, 21), fill=255)
rows = [("", "rind", "aws-lc"), ("Xeon", "228µs", "299µs"), ("M1 Pro", "284µs", "425µs"), ("Pi 5", "1.57ms", "1.33ms")]
for i, (a, b, c) in enumerate(rows):
    y = 23 + i * 10
    fnt = SANS_B if i == 0 else SANS
    text(d, (0, y), a, fnt, 9)
    text(d, (48, y), b, fnt, 9)
    text(d, (90, y), c, fnt, 9)
frames.append(("bench", f3))

lines = [
    "/* Generated by tools/gen_frames.py. 128x64, SSD1306 page order (8 pages x 128 cols, LSB = top row), 1 = lit. */",
    "#pragma once",
    "#include <stdint.h>",
    f"#define DEMO_FRAME_COUNT {len(frames)}",
]
for name, f in frames:
    px = f.load(); buf = []
    for page in range(8):
        for x in range(W):
            v = 0
            for bit in range(8):
                if px[x, page * 8 + bit]:
                    v |= 1 << bit
            buf.append(v)
    lines.append(f"static const uint8_t frame_{name}[1024] = {{")
    for i in range(0, 1024, 16):
        lines.append("  " + ", ".join(f"0x{b:02x}" for b in buf[i:i + 16]) + ",")
    lines.append("};")
lines.append("static const uint8_t *const demo_frames[DEMO_FRAME_COUNT] = {" + ", ".join(f"frame_{n}" for n, _ in frames) + "};")
os.makedirs(os.path.join(OUT, "oled_demo"), exist_ok=True)
open(os.path.join(OUT, "oled_demo", "frames.h"), "w").write("\n".join(lines) + "\n")

S = 4
def preview(f):
    big = Image.new("RGB", (W * S, H * S), (0, 0, 0))
    pb, pf = big.load(), f.load()
    for y in range(H):
        for x in range(W):
            if pf[x, y]:
                for dy in range(S):
                    for dx in range(S):
                        pb[x * S + dx, y * S + dy] = (235, 245, 255)
    return big

pad = 16
strip = Image.new("RGB", (W * S + 2 * pad, len(frames) * (H * S + pad) + pad), (40, 40, 40))
for i, (name, f) in enumerate(frames):
    p = preview(f)
    p.save(os.path.join(OUT, f"preview-{i+1}-{name}.png"))
    strip.paste(p, (pad, pad + i * (H * S + pad)))
strip.save(os.path.join(OUT, "preview.png"))
print("ok", [n for n, _ in frames])
